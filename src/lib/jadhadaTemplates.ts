export type ReadingKind = 'functional' | 'poetic' | 'serial'

export function detectReadingKind(subtitle: string): ReadingKind {
  if (subtitle.includes('شعري')) return 'poetic'
  if (subtitle.includes('مسترسل')) return 'serial'
  return 'functional'
}

export function readingSessions(kind: ReadingKind): SessionTemplate[] {
  if (kind === 'poetic') return READING_POETIC
  if (kind === 'serial') return READING_SERIAL
  return READING_FUNCTIONAL
}

export function writingSessions(unit: string): SessionTemplate[] {
  return unit === '1' ? WRITING_UNIT1 : WRITING_DEFAULT
}

/** رقم الأسبوع في التقويم السنوي (أسبوع التقويم التشخيصي غير محتسب) */
export function absoluteWeek(unit: string, weekInUnit: number): number {
  return (Number(unit) - 1) * 5 + weekInUnit
}

/** أسابيع الوحدة التي تُدرَّس فيها كل حصة، حسب المكوّن */
export function weeksForSession(comp: ComponentKey, unit: string, lessonIndex: number, session: number): number {
  if (comp === 'reading') return lessonIndex + 1          // نص لكل أسبوع
  if (comp === 'project') return session                    // حصة أسبوعياً
  if (comp === 'writing' && unit === '1') return session    // مرحلة في كل أسبوع
  // درسان × حصّتان: الدرس 1 في الأسبوعين 1-2، والدرس 2 في 3-4
  return lessonIndex * 2 + session
}

// ============================================================
//  حقن المحتوى الحقيقي في مراحل الحصة (لا كلام عام)
//  تعمل بنفس الطريقة على الدروس الجاهزة والمُدخَلة يدوياً معاً.
// ============================================================
function cloneSessions(sessions: SessionTemplate[]): SessionTemplate[] {
  return sessions.map(s => ({ ...s, stages: s.stages.map(st => ({ ...st, teacher: [...st.teacher], learner: [...st.learner] })) }))
}

function appendToStage(session: SessionTemplate, stageName: string, extra: { teacher?: string[]; learner?: string[] }) {
  const st = session.stages.find(s => s.stage === stageName)
  if (!st) return
  if (extra.teacher) st.teacher.push(...extra.teacher)
  if (extra.learner) st.learner.push(...extra.learner)
}

export type PhenomenonContent = { observation: string; rule: string; exercises: string[] }

/** يُنتج حصّتَي الظواهر اللغوية بمحتوى الدرس الحقيقي مزروعاً في مراحله */
export function enrichPhenomenonSessions(content: PhenomenonContent): SessionTemplate[] {
  const [s1, s2] = cloneSessions(PHENOMENA_SESSIONS)
  appendToStage(s1, 'الملاحظة والاكتشاف', { teacher: [`«${content.observation}»`] })
  appendToStage(s1, 'الاستنتاج', { teacher: [content.rule] })
  appendToStage(s1, 'التطبيق', { learner: content.exercises.map((e, i) => `${i + 1}. ${e}`) })
  appendToStage(s2, 'وضعية الانطلاق', { teacher: [`تذكير بالقاعدة: ${content.rule}`] })
  appendToStage(s2, 'إنجاز أنشطة التثبيت', { learner: content.exercises.map((e, i) => `${i + 1}. ${e}`) })
  return [s1, s2]
}

